{-# LANGUAGE LambdaCase #-}

{- |
Module      : Singular.Application.OpenDatum.HelpSnapshotSpec
Description : What a person reads from @open-datum --help@, pinned and held to the bar
License     : Apache-2.0

The help of the program and of every command is generated by the program and
compared with a committed snapshot, so changing it is a reviewed diff and
never an accident. Beside the snapshots, every page is held to what a user of
a command line is owed: the identity first, no setting without a description,
an overview that fits a screen, an example for every command that writes, and
the way a command ends.

Set @HELP_SNAPSHOT_RECORD=1@ to write the snapshots instead of comparing.
-}
module Singular.Application.OpenDatum.HelpSnapshotSpec (spec) where

import Control.Monad (forM_, unless)
import Data.List (isInfixOf, isPrefixOf)
import Data.Text qualified as T (pack, replace, unpack)
import Data.Version (showVersion)
import Singular.Application.OpenDatum.Command
    ( OpenDatumCommand (..)
    , openDatumHelp
    , openDatumHint
    , openDatumVersion
    , parseOpenDatumCommand
    , parseOpenDatumInvocation
    )
import Singular.Application.OpenDatum.Help (openDatumProgram)
import Singular.CLI.Options
    ( Leaf (..)
    , Node (..)
    , Program (..)
    , commandPaths
    , completionsFor
    , lintDeclaration
    )
import System.Directory (createDirectoryIfMissing)
import System.Environment (lookupEnv)
import Test.Hspec
    ( Spec
    , describe
    , it
    , shouldBe
    , shouldNotSatisfy
    , shouldReturn
    , shouldSatisfy
    )

program :: Program
program = openDatumProgram openDatumVersion

-- | Where the snapshots live, relative to the package.
snapshotDirectory :: FilePath
snapshotDirectory = "test/fixtures/help/open-datum"

-- | The page of a command with the version it was built as left out.
pageOf :: [String] -> String
pageOf path =
    T.unpack
        . T.replace (T.pack (showVersion openDatumVersion)) "VERSION"
        . T.pack
        $ openDatumHelp path

snapshotName :: [String] -> FilePath
snapshotName path =
    snapshotDirectory
        <> "/"
        <> (if null path then "overview" else foldr1 (\a b -> a <> "-" <> b) path)
        <> ".txt"

spec :: Spec
spec = describe "the help pages" $ do
    it "name every command the program declares" $
        commandPaths program
            `shouldBe` [ []
                       , ["create"]
                       , ["fold"]
                       , ["insert"]
                       , ["reclaim"]
                       , ["cleanup"]
                       , ["update"]
                       , ["terminate"]
                       ]
    it "are a well-formed declaration for the library" $
        lintDeclaration program `shouldBe` True
    forM_ (commandPaths program) $ \path ->
        describe (unwords ("open-datum" : path ++ ["--help"])) $ do
            it "matches its snapshot" $ do
                recording <- lookupEnv "HELP_SNAPSHOT_RECORD"
                case recording of
                    Just _ -> do
                        createDirectoryIfMissing True snapshotDirectory
                        writeFile (snapshotName path) (pageOf path)
                    Nothing -> do
                        expected <- readFile (snapshotName path)
                        pageOf path `shouldBe` expected
            it "opens with the identity of the build" $
                take 1 (lines (openDatumHelp path))
                    `shouldBe` [ "open-datum "
                                    <> showVersion openDatumVersion
                                    <> " (commit unknown)"
                               ]
            it "leaves no setting without a description" $
                pageOf path `shouldNotSatisfy` isInfixOf "undocumented"
    it "fit one screen as an overview" $
        length (lines (pageOf [])) `shouldSatisfy` (<= 45)
    it
        "never name a verb that lives in singular alone as a verb of its own"
        $ forM_ ["reject", "inspect"]
        $ \verb ->
            pageOf [] `shouldNotSatisfy` isInfixOf ("open-datum " <> verb)
    it
        "give every command that runs the way it ends, and every writer an example"
        $ forM_ (leaves (programNodes program))
        $ \(path, leaf) -> do
            pageOf path `shouldSatisfy` isInfixOf "Output and exit status:"
            unless (path == ["inspect"]) $
                pageOf path `shouldSatisfy` isInfixOf "Example:"
            unless (null (leafExamples leaf)) $
                pageOf path `shouldSatisfy` isInfixOf "Example:"
    it "answer --version with the identity alone" $
        parseOpenDatumCommand ["--version"]
            `shouldBe` Right
                ( OpenHelp
                    ( "open-datum "
                        <> showVersion openDatumVersion
                        <> " (commit unknown)\n"
                    )
                )
    it "name the commit the build carries" $
        fmap
            (\case OpenHelp page -> take 1 (lines page); _ -> [])
            ( fst
                <$> parseOpenDatumInvocation
                    [("SINGULAR_RELEASE_COMMIT", "0123abc")]
                    ["--version"]
            )
            `shouldBe` Right
                [ "open-datum "
                    <> showVersion openDatumVersion
                    <> " (commit 0123abc)"
                ]
    it "refuse with the usage of the command and where its help is" $ do
        let hint = openDatumHint ["insert", "--bogus"]
        hint
            `shouldSatisfy` any ("Usage: open-datum insert" `isPrefixOf`)
        drop (length hint - 1) hint
            `shouldBe` ["Try 'open-datum insert --help'."]
        length hint `shouldSatisfy` (<= 14)
    it "name the nearest command for a mistyped one" $
        openDatumHint ["inser", "--key", "k"]
            `shouldSatisfy` elem "Did you mean `open-datum insert`?"
    it "complete command and flag names" $ do
        completionsFor program ["ins"] 0 `shouldReturn` ["insert"]
        completionsFor program ["insert", "--pay"] 1
            `shouldReturn` ["--payload", "--payload-schema"]
    it "complete only the flags of the command asked about" $ do
        flagsOfFold <- completionsFor program ["fold", "--"] 1
        flagsOfFold `shouldSatisfy` elem "--pending"
        flagsOfFold `shouldSatisfy` notElem "--payload"
        flagsOfFold `shouldSatisfy` notElem "--payload-schema"
  where
    leaves = concatMap (collect [])
    collect prefix = \case
        Runs leaf -> [(prefix <> [leafName leaf], leaf)]
        Group name _ _ kids -> concatMap (collect (prefix <> [name])) kids
