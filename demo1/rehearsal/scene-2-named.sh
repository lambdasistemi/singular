#!/usr/bin/env bash
# Scene 2, Named: Alice creates a registry and registers the name alice with a
# payload in one command (insert --fold: book and fold). Each write signs from
# her vault in one command: it builds the run's one bundle, signs it, sends it
# and prints its receipt once every transaction has landed. The name ends
# active, its token in an application output. Comments say what each command
# does on the chain and on disk; after each write the cast shows what changed
# in her state directory and on chain. Her vault from scene 0 is in the
# directory too.
# shellcheck disable=SC2086  # the journal paths are globs over the run's directories the shell must expand
# shellcheck disable=SC2016  # the typed commands are shown verbatim on screen and evaluated by the tour helper
set -euo pipefail
export DEMO_TOTAL=4
# shellcheck disable=SC1091 # resolved from this script's own directory at runtime
. "$(dirname "$0")/lib.sh"
J='state/net-42/*/wallets/*/journal.jsonl'
play_cd "Alice works from a directory of her own." alice
play -p 5 $'The vault she made in scene 0, links to the release blueprint and the network time, and her\npayload. She signs from the vault.' \
  'ls'
play -p 6 $'Shorthand used below: the blueprint, the node with its network time, and her vault with the\ndescriptor her passphrase is read from (each command opens descriptor 3 itself).' \
  'echo "$BLUEPRINT"; echo "$NODE"; echo "$VAULT"'
play -p 5 "A directory for the commands' local state. No command has run yet, so it is empty." \
  'mkdir state && find state'
play -t -p 4 $'She creates a registry from her vault: one command builds the bundle that publishes its scripts\nand boots its state, signs it, sends it, and prints the receipt once all of it has landed.' \
  'open-datum create --state-dir state $BLUEPRINT $NODE $VAULT 3< ../vault-pass/alice > create.json'
# Bob is given only the state token (it is public); the later scenes read it from here.
# WORKAROUND: the state token is exported to the run's token.env between frames, and later commands say $TOKEN -> a user following the guide pastes the token from the create receipt into each command.
printf 'export TOKEN="--state-token %s"\n' "$(jq -r .stateToken create.json)" >"$RUN/token.env"
# shellcheck disable=SC1091 # generated by this scene into the run scratch directory
. "$RUN/token.env"
play -p 12 $'On chain: the registry exists, named by its state token; no key yet (the root is all zeros).\nThe receipt also prints the command that reads its page.' \
  'jq "{outcome, stateToken, root, describeCommand}" create.json | short'
play -p 14 $'Alice\'s local state directory: her journal of every transaction of the bundle, and the bundle\nwith its transactions, kept for recovery.' \
  'find state -type f | sort | short'
play -p 12 $'On disk: the journal, two lines for each transaction create sent: waiting-for-signatures when\nthe bundle was built, landed when the chain held it.' \
  "jq -r '.journalEvent + \"  \" + .journalStep' $J"
play -p 6 "The payload she will register with the name: what it points to, in her application." \
  'jq -c . payload.json'
play -t -p 4 $'She registers alice with her payload in one command: a bundle of two transactions, booking and
fold, signed and sent from her vault. The booking locks her deposit; the fold issues the token.' \
  'open-datum insert --key alice --payload payload.json --state-dir state $TOKEN $BLUEPRINT $NODE $VAULT --fold 3< ../vault-pass/alice > insert.json'
play -p 16 $'On chain: alice is registered. The request was booked and settled by the fold in one command,\nand the registry has a new root.' \
  'jq "{outcome, keyText, booking, fold, root, settled: [.settled[] | {edge, owner}]}" insert.json | short'
play -p 12 $'On disk: four new journal lines, for the two transactions: step book, then step fold, each\nwaiting-for-signatures when the bundle was built, then landed.' \
  "tail -n 4 $J | jq -c \"{journalStep, journalEvent, tx: (.journalTxId[0:8])}\""
play -p 12 $'What the command wrote in her state directory: the journal grew, and the bundle and its two\ntransactions are kept in submissions/ for recovery.' \
  'find state -type f -newer create.json | sort | short'
play -t -p 3 "She reads alice from the chain: a read; it writes nothing in her state directory." \
  'open-datum inspect --key alice --state-dir state $TOKEN $BLUEPRINT $NODE > inspect-alice.json'
play -p 16 $'On chain: alice is active. Its token is held in this application output, controlled by\nAlice\'s key, with her deposit.' \
  'jq "{leaf, keyText, applicationOutput: (.applicationOutput | {output, controller, deposit})}" inspect-alice.json | short'
play -t -p 3 "She reads the registry's page with the command the create receipt printed: a read of the chain." \
  'eval "$(jq -r .describeCommand create.json)" > page.txt'
play -p 18 $'The registry\'s state on chain: one active key (alice), one fold since create, nothing pending.' \
  'jq .state page.txt | short'
finish
