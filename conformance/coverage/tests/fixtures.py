"""Fixture builders for the coverage-gate tests.

Builds small synthetic Lean trees (statements module + lemmas + a definition)
with manifests generated by the REAL tools/check_model.py extraction, plus
record variants exercising each failure control. The mutations here are the
controls: every test must show the gate rejecting its mutation for the
intended reason.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[3]

STATEMENTS = """\
import Singular.Lemmas
namespace Singular
namespace Statements
/-- The greeter invariant: quantified over all n with the precondition. -/
theorem greeter_iff (n : Nat) (h : n > 0) : n + 0 = n := by
  simp
/-- A second public statement so the tree has two manifest rows. -/
theorem size_bound (items : List Nat) (h : items.length > 0) :
    items.length ≥ 1 := by
  simp
  exact h
end Statements
end Singular
"""

STATEMENTS_WEAKENED = """\
import Singular.Lemmas
namespace Singular
namespace Statements
/-- The greeter invariant, WEAKENED: the precondition is gone. -/
theorem greeter_iff (n : Nat) : n + 0 = n := by
  simp
/-- A second public statement so the tree has two manifest rows. -/
theorem size_bound (items : List Nat) (h : items.length > 0) :
    items.length ≥ 1 := by
  simp
  exact h
end Statements
end Singular
"""

MODEL = """\
namespace Singular
def greeter (n : Nat) : Nat := n + 0
end Singular
"""

LEMMA_FILES = {
    "lemmas": """\
import Singular.Model
namespace Singular
@[simp] theorem attributed_zero (n : Nat) : n + 0 = n := rfl
theorem helper.dotted (n : Nat) : n = n := rfl
theorem primed_helper' (n : Nat) : n = n := rfl
end Singular
""",
    "weakened_lemmas": None,  # lemmas unchanged in the statement-edit variant
}


NAMING_STUBS = {
    "lean/Singular/NamingStatements.lean": (
        "namespace Singular.NamingStatements\n"
        "theorem naming_stub_iff (n : Nat) (h : n > 0) : n + 0 = n := by\n  simp\n"
        "end Singular.NamingStatements\n"
    ),
    "lean/Singular/NamingLifecycleStatements.lean": (
        "namespace Singular.NamingLifecycleStatements\n"
        "theorem lifecycle_stub_iff (n : Nat) (h : n > 0) : n + 0 = n := by\n  simp\n"
        "end Singular.NamingLifecycleStatements\n"
    ),
    "lean/Singular/NamingWireStatements.lean": (
        "namespace Singular.NamingWireStatements\n"
        "theorem wire_stub_iff (n : Nat) (h : n > 0) : n + 0 = n := by\n  simp\n"
        "end Singular.NamingWireStatements\n"
    ),
}


def build_base_tree(root: Path) -> None:
    """A synthetic lean/ tree: 5 manifest-bound + 3 unclassified obligations."""
    (root / "lean/Singular").mkdir(parents=True)
    (root / "lean/Singular/Statements.lean").write_text(STATEMENTS)
    for rel, text in NAMING_STUBS.items():
        (root / rel).write_text(text)
    (root / "lean/Singular/Model.lean").write_text(MODEL)
    (root / "lean/Singular/Lemmas.lean").write_text(LEMMA_FILES["lemmas"])
    (root / "lean/Singular.lean").write_text("import Singular.Model\n")
    export_manifests(root)


def export_manifests(root: Path) -> None:
    """Regenerate every fixture manifest with check_model.statement_inventory.

    Using the real extraction keeps the fixture honest: identity comes from
    the same code path as production, never from a hand-written digest. The
    module/manifest pairing is the production one (inventory.STATEMENT_MODULES).
    """
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
    from singular_coverage.inventory import STATEMENT_MODULES

    sys.path.insert(0, str(REPO_ROOT / "tools"))
    try:
        import check_model

        for rel, prefix, manifest_rel in STATEMENT_MODULES:
            records = check_model.statement_inventory(root / rel, prefix)
            (root / manifest_rel).write_text(json.dumps(records, indent=2) + "\n")
    finally:
        sys.path.remove(str(REPO_ROOT / "tools"))
        sys.path.remove(str(Path(__file__).resolve().parents[1]))


def build_variant(base: Path, variant: str) -> Path:
    """Copy the base fixture tree and apply a named mutation."""
    import shutil

    root = base.parent / f"tree-{variant}"
    if root.exists():
        shutil.rmtree(root)
    shutil.copytree(base, root)
    if variant == "statement-edit":
        (root / "lean/Singular/Statements.lean").write_text(STATEMENTS_WEAKENED)
        export_manifests(root)
    elif variant == "theorem-removed":
        text = (root / "lean/Singular/Statements.lean").read_text()
        start = text.index("/-- A second public statement")
        end = text.index("end Statements")
        (root / "lean/Singular/Statements.lean").write_text(text[:start] + text[end:])
        export_manifests(root)
    elif variant == "definition-changed":
        (root / "lean/Singular/Model.lean").write_text(
            "namespace Singular\ndef greeter (n : Nat) : Nat := n - 0\nend Singular\n"
        )
    elif variant == "unknown-grammar":
        # an unrecognized declaration form: one keyword occurrence the
        # scanner cannot account for must fail the scan, not shrink the count
        with (root / "lean/Singular/Lemmas.lean").open("a") as fh:
            fh.write("\ntheorem 5bad (n : Nat) : n = n := rfl\n")
    else:
        raise ValueError(f"unknown variant {variant}")
    return root


