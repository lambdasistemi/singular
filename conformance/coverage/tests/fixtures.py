def identity_of(root: Path, name: str) -> str:
    """name@statementSha256 for a fixture obligation, via the real inventory."""
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
    from singular_coverage.inventory import build_inventory

    obligation = build_inventory(root).by_name()[name]
    return obligation.identity


def full_check(root: Path, *, layer: str, execution: str, check_id: str, name: str,
               definition_digest: str, candidate: str, **evidence_overrides) -> dict:
    """A structurally valid, executed, fresh, non-vacuous check row."""
    evidence = {
        "status": "pass",
        "candidateDigest": candidate,
        "candidatePaths": ["src"],
        "command": "nix run .#example-check",
        "seed": "142857",
        "cases": 100,
        "discards": 3,
        "thenAssertions": 2,
        "resultDigest": "a" * 64,
    }
    evidence.update(evidence_overrides)
    from singular_coverage.inventory import build_inventory

    digest = build_inventory(root).by_name()[name].statementSha256
    return {
        "checkId": check_id,
        "obligation": name,
        "statementSha256": digest,
        "layer": layer,
        "executionIdentity": execution,
        "entryPoints": ["src/Greeter.hs:greeter"],
        "definitionDigests": {"Singular.greeter": definition_digest},
        "evidence": evidence,
        "control": {"kind": "mutation", "target": "Singular.greeter", "status": "valid"},
    }


def mapping_row(root: Path, name: str, story_id: str) -> dict:
    from singular_coverage.inventory import build_inventory

    digest = build_inventory(root).by_name()[name].statementSha256
    return {
        "obligation": name,
        "statementSha256": digest,
        "storyId": story_id,
        "clauses": {
            "given": ["n : Nat", "h : n > 0"],
            "when": ["n + 0"],
            "then": ["result = n"],
        },
        "vocabulary": {"greeter": "Singular.greeter"},
    }


def write_record(root: Path, record: dict, name: str = "record.json") -> Path:
    """Write a record, injecting the live discovered population if absent."""
    if "discoveredPopulation" not in record:
        from singular_coverage.inventory import build_inventory

        record["discoveredPopulation"] = sorted(build_inventory(root).by_identity())
    path = root / name
    path.write_text(json.dumps(record, indent=2) + "\n")
    return path
