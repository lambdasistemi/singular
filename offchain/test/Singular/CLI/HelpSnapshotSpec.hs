{-# LANGUAGE LambdaCase #-}

{- |
Module      : Singular.CLI.HelpSnapshotSpec
Description : What a person reads from @singular --help@, pinned and held to the bar
License     : Apache-2.0

The help of the program and of every command is generated by the program and
compared with a committed snapshot, so changing it is a reviewed diff and
never an accident. Beside the snapshots, every page is held to what a user of
a command line is owed: the identity first, no setting without a description,
an overview that fits a screen, an example for every command that writes, and
the way a command ends.

Set @HELP_SNAPSHOT_RECORD=1@ to write the snapshots instead of comparing.
-}
module Singular.CLI.HelpSnapshotSpec (spec) where

import Control.Monad (forM_, unless)
import Data.List (isInfixOf, isPrefixOf)
import Data.Text qualified as T (pack, replace, unpack)
import Data.Version (showVersion)
import Singular.CLI.Command
    ( CLIError (..)
    , Command (..)
    , parseCommand
    , parseInvocation
    , singularHint
    , singularVersion
    )
import Singular.CLI.Help (singularHelp, singularProgram)
import Singular.CLI.Options
    ( Leaf (..)
    , Node (..)
    , Program (..)
    , commandPaths
    , completionsFor
    , lintDeclaration
    , resolvePath
    )
import System.Directory (createDirectoryIfMissing)
import System.Environment (lookupEnv)
import Test.Hspec
    ( Spec
    , describe
    , it
    , shouldBe
    , shouldNotSatisfy
    , shouldReturn
    , shouldSatisfy
    )

program :: Program
program = singularProgram singularVersion

-- | Where the snapshots live, relative to the package.
snapshotDirectory :: FilePath
snapshotDirectory = "test/fixtures/help/singular"

-- | The page of a command with the version it was built as left out.
pageOf :: [String] -> String
pageOf path =
    T.unpack
        . T.replace (T.pack (showVersion singularVersion)) "VERSION"
        . T.pack
        $ singularHelp singularVersion [] path

snapshotName :: [String] -> FilePath
snapshotName path =
    snapshotDirectory
        <> "/"
        <> (if null path then "overview" else foldr1 (\a b -> a <> "-" <> b) path)
        <> ".txt"

spec :: Spec
spec = describe "the help pages" $ do
    it "name every command, and only commands the program declares" $
        commandPaths program
            `shouldSatisfy` \paths ->
                [] `elem` paths
                    && ["registry", "create"] `elem` paths
                    && ["wallet", "sign"] `elem` paths
                    && ["submit"] `elem` paths
                    && ["registry"] `elem` paths
                    && ["registry", "create"] `elem` paths
                    && length paths == 9
    it "refuses the removed registry address command" $
        parseCommand ["registry", "address"]
            `shouldBe` Left (UnknownCommand ["registry", "address"])
    it "refuses the removed registry page command" $
        parseCommand ["registry", "describe"]
            `shouldBe` Left (UnknownCommand ["registry", "describe"])
    it "are a well-formed declaration for the library" $
        lintDeclaration program `shouldBe` True
    forM_ (commandPaths program) $ \path ->
        describe (unwords ("singular" : path ++ ["--help"])) $ do
            it "matches its snapshot" $ do
                recording <- lookupEnv "HELP_SNAPSHOT_RECORD"
                case recording of
                    Just _ -> do
                        createDirectoryIfMissing True snapshotDirectory
                        writeFile (snapshotName path) (pageOf path)
                    Nothing -> do
                        expected <- readFile (snapshotName path)
                        pageOf path `shouldBe` expected
            it "opens with the identity of the build" $
                take 1 (lines (singularHelp singularVersion [] path))
                    `shouldBe` [ "singular "
                                    <> showVersion singularVersion
                                    <> " (commit unknown)"
                               ]
            it "leaves no setting without a description" $
                pageOf path `shouldNotSatisfy` isInfixOf "undocumented"
    it "fit one screen as an overview" $
        length (lines (pageOf [])) `shouldSatisfy` (<= 45)
    it "carry an example and the way they end for every command that runs" $
        forM_ (leaves (programNodes program)) $ \(path, leaf) -> do
            pageOf path `shouldSatisfy` isInfixOf "Output and exit status:"
            unless (null (leafExamples leaf)) $
                pageOf path `shouldSatisfy` isInfixOf "Example:"
    it "give every command that writes an example" $
        forM_ writes $ \path ->
            pageOf path `shouldSatisfy` isInfixOf "Example:"
    it "answer --version with the identity alone" $
        parseCommand ["--version"]
            `shouldBe` Right
                ( Help
                    ( "singular "
                        <> showVersion singularVersion
                        <> " (commit unknown)\n"
                    )
                )
    it "name the commit the build carries" $
        fmap
            (\case Help page -> take 1 (lines page); _ -> [])
            ( fst
                <$> parseInvocation
                    [("SINGULAR_RELEASE_COMMIT", "0123abc")]
                    ["--version"]
            )
            `shouldBe` Right
                [ "singular "
                    <> showVersion singularVersion
                    <> " (commit 0123abc)"
                ]
    forM_ ["fold", "reject", "reclaim"] $ \verb ->
        it ("refuses the removed registry " <> verb <> " command") $
            parseCommand ["registry", verb]
                `shouldBe` Left (UnknownCommand ["registry", verb])
    it "refuse with the usage of the command and where its help is" $ do
        let hint = singularHint ["registry", "create", "--bogus"]
        hint
            `shouldSatisfy` any ("Usage: singular registry create" `isPrefixOf`)
        drop (length hint - 1) hint
            `shouldBe` ["Try 'singular registry create --help'."]
    it "name the nearest command for a mistyped one" $
        singularHint ["walet", "create"]
            `shouldSatisfy` elem "Did you mean `singular wallet`?"
    it "stop a command line at the commands it names" $
        resolvePath program ["registry", "create", "extra"]
            `shouldBe` (["registry", "create"], ["extra"])
    it "complete command and flag names" $ do
        completionsFor program ["registry", "c"] 1 `shouldReturn` ["create"]
        completionsFor program ["registry", "create", "--bl"] 2
            `shouldReturn` ["--blueprint"]
        completionsFor program ["w"] 0 `shouldReturn` ["wallet"]
    it "complete only the flags of the command asked about" $ do
        flagsInferred <- completionsFor program ["wallet", "sign", "--"] 2
        flagsInferred `shouldSatisfy` elem "--vault"
        flagsInferred `shouldSatisfy` notElem "--blueprint"
  where
    leaves = concatMap (collect [])
    collect prefix = \case
        Runs leaf -> [(prefix <> [leafName leaf], leaf)]
        Group name _ _ kids -> concatMap (collect (prefix <> [name])) kids
    writes =
        [ ["registry", "create"]
        , ["wallet", "create"]
        , ["wallet", "sign"]
        , ["submit"]
        ]
