{- |
Module      : Singular.Registry.ContractSuite
Description : #326 — one backend contract, every adapter
License     : Apache-2.0

The read interface's contract, written once and run against every
adapter: the deterministic in-memory chain, a node reached by socket and
magic, and the index that follows a node. Each case is a requirement a
backend meets or refuses by name; an adapter that cannot exercise a case
says so in its harness, with the reason, and the suite reports that
case for that adapter as not supported — never as passed, and never
decided by catching a failure.

Every run names its evidence class: @test-adapter@ for a chain held in
memory, @devnet@ for a development node. No class names a public chain.

Every value a case compares against is read from the adapter at run
time — the point of a view, the outputs a fresh view answers — and the
chain change a consistency case makes is observed through another
route than the view under test, so a case cannot pass by reading what
it wrote.
-}
