-- | The contract's @quorumKeyHash@: the 28 bytes @start..start+27@.
quorumKeyHash :: Word8 -> ByteString
quorumKeyHash start = BS.pack [start .. start + 27]

-- | The contract's enterprise payment-key address on network 1 with
-- payment hash @quorumKeyHash start@ — bytes @61 start … start+27@.
enterpriseAddress :: Word8 -> Address
enterpriseAddress start = case decodeAddress (BS.cons 0x61 (quorumKeyHash start)) of
  Just a -> a
  Nothing -> error "Vectors.enterpriseAddress: canonical address refused"

