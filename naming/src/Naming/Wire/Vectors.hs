-- | @WD03@'s @encoded@ datum: the canonical datum with the payment
-- destination replaced by @constr(1,[bytes, bytes])@ — two destination
-- addresses (bytes @61 55…@ and @61 71…@), refused (@result: null@).
wd03Encoded :: WireData
wd03Encoded = case encodeNamingDatum wd01Fixture of
  Constr 0 [Constr 0 [control, _destination, commitment, quorum]] ->
    Constr 0
      [ Constr 0
          [ control
          , Constr 1
              [ WBytes (destinationBytes 85)
              , WBytes (destinationBytes 113)
              ]
          , commitment
          , quorum
          ]
      ]
  _ -> error "Vectors.wd03Encoded: WD01 fixture lost its canonical shape"
  where
    destinationBytes start = BS.cons 0x61 (quorumKeyHash start)

